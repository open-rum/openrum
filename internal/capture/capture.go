// Package capture holds the per-project rules that decide which API Requests
// may carry HTTP headers into storage.
//
// Nothing is captured by default. A project with no rules stores no header at
// all, and the consumer enforces that regardless of what an SDK sends: a write
// key is public, so the browser's behaviour can only be an optimisation.
package capture

import (
	"errors"
	"fmt"
	"slices"
	"strings"

	"openrum/internal/filter"
	"openrum/internal/privacy"
)

// RetentionDays is how long a stored header snapshot is readable. The same
// number is written into the ClickHouse column TTL; the query layer also cuts
// at it, because ClickHouse removes expired column values during merges, not at
// the moment they expire.
const RetentionDays = 3

const (
	MaxRules         = 20
	MaxPatternLength = 300
	MaxWildcards     = 10
	MaxRuleIDLength  = 64
	MaxNoteLength    = 200
)

// AnyMethod matches every HTTP method.
const AnyMethod = "*"

var (
	ErrInvalidSettings = errors.New("invalid API capture settings")

	methods = []string{"GET", "POST", "PUT", "PATCH", "DELETE", "HEAD", "OPTIONS"}
)

// Rule opts one API, or a family of them, in to header capture.
type Rule struct {
	ID string `json:"id"`
	// Method is an HTTP method or AnyMethod.
	Method string `json:"method"`
	// Pattern is matched against the normalized endpoint, the same address the
	// API monitoring page shows (`https://api.example.com/orders/:id`). `*` is
	// the only wildcard.
	Pattern         string   `json:"pattern"`
	RequestHeaders  []string `json:"requestHeaders,omitempty"`
	ResponseHeaders []string `json:"responseHeaders,omitempty"`
	// RequestBody and ResponseBody opt in to a redacted, size-limited copy of the body.
	// They are separate from the headers and from each other: a project that wants
	// `content-type` has not agreed to store payloads.
	RequestBody  bool   `json:"requestBody,omitempty"`
	ResponseBody bool   `json:"responseBody,omitempty"`
	Note         string `json:"note,omitempty"`
}

// Settings is the stored document. The zero value captures nothing.
type Settings struct {
	Rules []Rule `json:"rules,omitempty"`
}

// Methods lists the HTTP methods a rule can name.
func Methods() []string { return slices.Clone(methods) }

// Validate reports whether the settings can be stored.
func (settings Settings) Validate() error {
	if len(settings.Rules) > MaxRules {
		return fmt.Errorf("%w: %d rules exceeds the limit of %d", ErrInvalidSettings, len(settings.Rules), MaxRules)
	}
	seen := make(map[string]struct{}, len(settings.Rules))
	for _, rule := range settings.Rules {
		if err := rule.validate(); err != nil {
			return err
		}
		if _, duplicate := seen[rule.ID]; duplicate {
			return fmt.Errorf("%w: duplicate rule id %q", ErrInvalidSettings, rule.ID)
		}
		seen[rule.ID] = struct{}{}
	}
	return nil
}

// label names a rule in an error by what a person typed. The identifier is generated by
// the Console, so quoting it would tell the reader nothing.
func (rule Rule) label() string {
	if strings.TrimSpace(rule.Pattern) != "" {
		return fmt.Sprintf("for %q", rule.Pattern)
	}
	return fmt.Sprintf("%q", rule.ID)
}

func (rule Rule) validate() error {
	switch {
	case rule.ID == "" || len(rule.ID) > MaxRuleIDLength:
		return fmt.Errorf("%w: rule id must be between 1 and %d characters", ErrInvalidSettings, MaxRuleIDLength)
	case rule.Method != AnyMethod && !slices.Contains(methods, rule.Method):
		return fmt.Errorf("%w: rule %s has unknown method %q", ErrInvalidSettings, rule.label(), rule.Method)
	case strings.TrimSpace(rule.Pattern) == "":
		return fmt.Errorf("%w: rule %s needs a pattern", ErrInvalidSettings, rule.label())
	case len(rule.Pattern) > MaxPatternLength:
		return fmt.Errorf("%w: rule %s pattern exceeds %d characters", ErrInvalidSettings, rule.label(), MaxPatternLength)
	case strings.Count(rule.Pattern, "*") > MaxWildcards:
		return fmt.Errorf("%w: rule %s uses more than %d wildcards", ErrInvalidSettings, rule.label(), MaxWildcards)
	case strings.Trim(rule.Pattern, "*/") == "":
		// A rule that matches every request is the opposite of per-API opt-in.
		return fmt.Errorf("%w: rule %s must name a host or path, not only wildcards", ErrInvalidSettings, rule.label())
	case len(rule.Note) > MaxNoteLength:
		return fmt.Errorf("%w: rule %s note exceeds %d characters", ErrInvalidSettings, rule.label(), MaxNoteLength)
	case len(rule.RequestHeaders) == 0 && len(rule.ResponseHeaders) == 0 && !rule.RequestBody && !rule.ResponseBody:
		return fmt.Errorf("%w: rule %s must name at least one header or capture a body", ErrInvalidSettings, rule.label())
	}
	if err := validateHeaderNames(rule.label(), "request", rule.RequestHeaders); err != nil {
		return err
	}
	return validateHeaderNames(rule.label(), "response", rule.ResponseHeaders)
}

func validateHeaderNames(rule, direction string, names []string) error {
	if len(names) > privacy.MaxHeaders {
		return fmt.Errorf("%w: rule %s lists more than %d %s headers", ErrInvalidSettings, rule, privacy.MaxHeaders, direction)
	}
	seen := make(map[string]struct{}, len(names))
	for _, name := range names {
		switch {
		case !privacy.ValidHeaderName(name):
			return fmt.Errorf("%w: rule %s has an invalid %s header name %q; use lower-case letters, digits and hyphens", ErrInvalidSettings, rule, direction, name)
		case privacy.SensitiveHeader(name):
			return fmt.Errorf("%w: rule %s cannot capture %q; headers that carry credentials, sessions or client addresses are never stored", ErrInvalidSettings, rule, name)
		}
		if _, duplicate := seen[name]; duplicate {
			return fmt.Errorf("%w: rule %s lists %s header %q twice", ErrInvalidSettings, rule, direction, name)
		}
		seen[name] = struct{}{}
	}
	return nil
}

// Normalize lower-cases and trims what a person typed, so the stored document
// is canonical. Validation runs on the result.
func (settings Settings) Normalize() Settings {
	normalized := Settings{}
	for _, rule := range settings.Rules {
		rule.ID = strings.TrimSpace(rule.ID)
		rule.Method = strings.ToUpper(strings.TrimSpace(rule.Method))
		if rule.Method == "" {
			rule.Method = AnyMethod
		}
		rule.Pattern = strings.TrimSpace(rule.Pattern)
		rule.Note = strings.TrimSpace(rule.Note)
		rule.RequestHeaders = normalizeNames(rule.RequestHeaders)
		rule.ResponseHeaders = normalizeNames(rule.ResponseHeaders)
		normalized.Rules = append(normalized.Rules, rule)
	}
	return normalized
}

func normalizeNames(names []string) []string {
	var result []string
	for _, name := range names {
		if name = strings.ToLower(strings.TrimSpace(name)); name != "" {
			result = append(result, name)
		}
	}
	return result
}

// ClientProjection is what a browser is sent.
//
// Patterns are written against the normalized endpoint, in which identifier-like
// path segments have become `:id`. A browser holds the original address, and
// re-implementing the substitution there would let the two disagree. So each
// `:id` is widened to `*` instead. The browser then matches a superset of what
// the consumer accepts; the consumer still decides what is stored, so the cost of
// the widening is a few bytes in memory and on the wire, never extra storage.
func (settings Settings) ClientProjection() Settings {
	projected := Settings{}
	for _, rule := range settings.Rules {
		rule.Pattern = strings.ReplaceAll(rule.Pattern, ":id", "*")
		rule.Note = ""
		projected.Rules = append(projected.Rules, rule)
	}
	return projected
}

// Compiled is the evaluable form of Settings.
type Compiled struct{ rules []compiledRule }

type compiledRule struct {
	rule    Rule
	pattern filter.Glob
}

// Compile prepares settings for matching. Invalid settings are rejected, so a
// stored document that no longer validates fails closed instead of capturing
// something the current rules would refuse.
func Compile(settings Settings) (*Compiled, error) {
	if err := settings.Validate(); err != nil {
		return nil, err
	}
	compiled := &Compiled{rules: make([]compiledRule, 0, len(settings.Rules))}
	for _, rule := range settings.Rules {
		compiled.rules = append(compiled.rules, compiledRule{rule: rule, pattern: filter.CompileGlob(rule.Pattern)})
	}
	return compiled, nil
}

// Active reports whether any rule exists. A nil receiver is inactive.
func (compiled *Compiled) Active() bool { return compiled != nil && len(compiled.rules) > 0 }

// Selection is the union of the headers every matching rule allows.
type Selection struct {
	Request      []string
	Response     []string
	RequestBody  bool
	ResponseBody bool
}

// Empty reports whether nothing may be captured.
func (selection Selection) Empty() bool {
	return len(selection.Request) == 0 && len(selection.Response) == 0 && !selection.RequestBody && !selection.ResponseBody
}

// Select returns what may be captured for one request. Several rules can match
// one endpoint, for instance a family pattern and a specific one; the result is
// the union rather than the first match, so the order of the list never changes
// what is stored.
func (compiled *Compiled) Select(method, endpoint string) Selection {
	var selection Selection
	if !compiled.Active() {
		return selection
	}
	for _, candidate := range compiled.rules {
		if candidate.rule.Method != AnyMethod && candidate.rule.Method != method {
			continue
		}
		if !candidate.pattern.Match(endpoint) {
			continue
		}
		selection.Request = union(selection.Request, candidate.rule.RequestHeaders)
		selection.Response = union(selection.Response, candidate.rule.ResponseHeaders)
		selection.RequestBody = selection.RequestBody || candidate.rule.RequestBody
		selection.ResponseBody = selection.ResponseBody || candidate.rule.ResponseBody
	}
	return selection
}

func union(current, extra []string) []string {
	for _, name := range extra {
		if !slices.Contains(current, name) {
			current = append(current, name)
		}
	}
	return current
}

// Restrict keeps only the allowed names of a header snapshot. Names compare in
// lower case. It returns nil when nothing remains.
func Restrict(headers map[string]string, allowed []string) map[string]string {
	if len(headers) == 0 || len(allowed) == 0 {
		return nil
	}
	var kept map[string]string
	for name, value := range headers {
		if slices.Contains(allowed, strings.ToLower(name)) {
			if kept == nil {
				kept = make(map[string]string, len(allowed))
			}
			kept[strings.ToLower(name)] = value
		}
	}
	return kept
}
